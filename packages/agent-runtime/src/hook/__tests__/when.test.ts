/**
 * 触发绑定的 CEL `when`（compileWhen / evaluateWhen）。
 *
 * 两个时机：解析期 compileWhen 只查语法（语法错 → 整份文件非法）；fire 时 evaluateWhen
 * 严格求值 —— 缺失属性、未知变量、非布尔结果一律 throw，由 runner 兜成「不命中 + 告警」。
 * 这里钉的是「严格」本身：宽松一步（缺属性当 false、非布尔按真值）就会让写错字段名的 hook
 * 静默地永远不跑或永远在跑。
 *
 * 宿主函数（HW-11…18）：`activeSessions(date)` 的签名登记在 when.ts，实现由宿主经 setWhenHostFunctions 注入 ——
 * 没注入 / 日期形状不对 / 实现抛错都是求值错误；只有表达式真的求值到它时才调用（短路）。
 *
 * 每次求值的宿主函数（HW-19…25，`evaluateWhen` 的第三个参数）：只给这一次求值换上，全局那份不被调、
 * 求值之后（含抛错、非布尔）原样换回；`{}` 不动全局；编译缓存不捕获实现；日期形状照查。
 */
import { afterEach, describe, expect, it, vi } from 'vitest'
import { compileWhen, evaluateWhen, setWhenHostFunctions } from '../when'

/** 内置 auto-title 精修绑定的条件（最复杂的真实表达式） */
const REFINE = 'event.titleAutoGenerated && event.turnCount == 2 && event.textMessageCount >= 3'

describe('compileWhen — 解析期只查语法', () => {
  it.each([
    'event.isDefaultTitle',
    REFINE,
    'has(event.x)',
    "event.p in ['work', 'chat']",
    "event.t.contains('x')",
    'size(event.t) > 0',
    "env.host == 'desktop'"
  ])('HW-1 合法表达式 %s → null', (expression) => {
    expect(compileWhen(expression)).toBeNull()
  })

  it.each(['event.', 'event.a &&', '', '   ', 'event.a === 1'])(
    'HW-2 语法错 %j → 非空错误消息',
    (expression) => {
      const error = compileWhen(expression)
      expect(typeof error).toBe('string')
      expect(error!.trim().length).toBeGreaterThan(0)
    }
  )
})

describe('evaluateWhen — fire 时严格求值', () => {
  it('HW-3 布尔结果原样返回（字段 true / false，字面量 true）', () => {
    expect(evaluateWhen('event.isDefaultTitle', { event: { isDefaultTitle: true } })).toBe(true)
    expect(evaluateWhen('event.isDefaultTitle', { event: { isDefaultTitle: false } })).toBe(false)
    expect(evaluateWhen('true', { event: {}, env: {} })).toBe(true)
  })

  it('HW-4 非布尔结果 throw（字符串 → got string；1 + 1 是 BigInt → got bigint）', () => {
    expect(() => evaluateWhen('event.title', { event: { title: 'New Chat' } })).toThrow(
      'when expression must evaluate to a boolean, got string'
    )
    expect(() => evaluateWhen('1 + 1', { event: {}, env: {} })).toThrow(
      'when expression must evaluate to a boolean, got bigint'
    )
  })

  it('HW-5 严格访问：缺失属性 / 未知顶层变量 / event 为 null 都 throw', () => {
    expect(() => evaluateWhen('event.nope', { event: {} })).toThrow(/No such key: nope/)
    expect(() => evaluateWhen('vars.a == 1', { event: {}, env: {} })).toThrow(
      /Unknown variable: vars/
    )
    expect(() => evaluateWhen('event.isDefaultTitle', { event: null })).toThrow()
  })

  it('HW-6 has() 是探测缺失字段的正路 → false，不 throw', () => {
    expect(evaluateWhen('has(event.nope)', { event: {} })).toBe(false)
  })

  it('HW-7 上下文 {event, env} 都可达（event.trigger 与 env.platform）', () => {
    expect(
      evaluateWhen("event.trigger == 'session.prompt-accepted' && env.platform == 'darwin'", {
        event: { trigger: 'session.prompt-accepted' },
        env: { host: 'desktop', platform: 'darwin' }
      })
    ).toBe(true)
  })

  it('HW-8 短路：false && event.nope → false（右侧缺失属性不求值）', () => {
    expect(evaluateWhen('false && event.nope', { event: {} })).toBe(false)
  })

  it('HW-9 编译缓存不冻结上下文：同一表达式换 payload 结论跟着变', () => {
    const expression = 'event.turnCount == 2'
    expect(evaluateWhen(expression, { event: { turnCount: 2 } })).toBe(true)
    expect(evaluateWhen(expression, { event: { turnCount: 3 } })).toBe(false)
    expect(evaluateWhen(expression, { event: { turnCount: 2 } })).toBe(true)
  })

  it("HW-10 类型严格：'2' == 2 为 false；数字比较照常", () => {
    expect(evaluateWhen('event.turnCount == 2', { event: { turnCount: '2' } })).toBe(false)
    expect(evaluateWhen('event.turnCount >= 3', { event: { turnCount: 3 } })).toBe(true)
    expect(evaluateWhen('event.turnCount >= 3', { event: { turnCount: 2 } })).toBe(false)
  })
})

describe('宿主函数 activeSessions(date)', () => {
  // 进程级注入：每条用例后清空，免得串到别的用例
  afterEach(() => {
    setWhenHostFunctions({})
  })

  /** 日报 bot 的真实条件 */
  const DAILY = "event.local.time == '18:00' && activeSessions(event.local.date) > 0"
  const at = (time: string): Record<string, unknown> => ({
    event: { trigger: 'timer.fired', local: { date: '2026-10-24', time } },
    env: { host: 'desktop' }
  })

  it('HW-11 注入后可调、返回 int：== 3 与 > 0 都为真；实现收到的是那个日期串', () => {
    const impl = vi.fn((_date: string) => 3)
    setWhenHostFunctions({ activeSessions: impl })
    expect(evaluateWhen("activeSessions('2026-10-24') == 3", { event: {}, env: {} })).toBe(true)
    expect(evaluateWhen("activeSessions('2026-10-24') > 0", { event: {}, env: {} })).toBe(true)
    expect(impl).toHaveBeenCalledTimes(2)
    expect(impl).toHaveBeenNthCalledWith(1, '2026-10-24')
  })

  it('HW-12 没注入 → 求值 throw「not available on this host」', () => {
    setWhenHostFunctions({})
    expect(() => evaluateWhen("activeSessions('2026-10-24') > 0", { event: {}, env: {} })).toThrow(
      'not available on this host'
    )
  })

  it.each(['2026-1-5', '20261024', '', '2026-10-24T00:00'])(
    'HW-13 日期形状不对 %j → throw「expects a local date like」，实现不被调用',
    (date) => {
      const impl = vi.fn((_date: string) => 1)
      setWhenHostFunctions({ activeSessions: impl })
      expect(() =>
        evaluateWhen('activeSessions(event.d) > 0', { event: { d: date }, env: {} })
      ).toThrow("expects a local date like '2026-10-24'")
      expect(impl).not.toHaveBeenCalled()
    }
  )

  it('HW-14 懒调用：&& / || / ?: 短路到不了它就不调；日报条件 17:59 不调、18:00 恰调一次且传 event.local.date', () => {
    const impl = vi.fn((_date: string) => 5)
    setWhenHostFunctions({ activeSessions: impl })
    const ctx = { event: {}, env: {} }
    expect(evaluateWhen("false && activeSessions('2026-10-24') > 0", ctx)).toBe(false)
    expect(evaluateWhen("true || activeSessions('2026-10-24') > 0", ctx)).toBe(true)
    expect(evaluateWhen("true ? false : activeSessions('2026-10-24') > 0", ctx)).toBe(false)
    expect(evaluateWhen(DAILY, at('17:59'))).toBe(false)
    expect(impl).not.toHaveBeenCalled()

    expect(evaluateWhen(DAILY, at('18:00'))).toBe(true)
    expect(impl).toHaveBeenCalledTimes(1)
    expect(impl).toHaveBeenCalledWith('2026-10-24')
  })

  it.each(['activeSessions(1) > 0', 'activeSession(event.local.date) > 0', "nosuch('a')"])(
    'HW-15 （钉现状）解析期只查语法：%s → compileWhen 为 null，求值时才 throw',
    (expression) => {
      setWhenHostFunctions({ activeSessions: () => 1 })
      expect(compileWhen(expression)).toBeNull()
      expect(() =>
        evaluateWhen(expression, { event: { local: { date: '2026-10-24' } }, env: {} })
      ).toThrow('found no matching overload')
    }
  )

  it('HW-16 setWhenHostFunctions 整体替换：先注入再传 {} → 第二次求值 throw', () => {
    setWhenHostFunctions({ activeSessions: () => 1 })
    expect(evaluateWhen("activeSessions('2026-10-24') > 0", { event: {}, env: {} })).toBe(true)
    setWhenHostFunctions({})
    expect(() => evaluateWhen("activeSessions('2026-10-24') > 0", { event: {}, env: {} })).toThrow(
      'not available on this host'
    )
  })

  it('HW-17 实现自己抛错 → evaluateWhen throw（调用方按不命中处置）', () => {
    setWhenHostFunctions({
      activeSessions: () => {
        throw new Error('calendar index down')
      }
    })
    expect(() => evaluateWhen("activeSessions('2026-10-24') > 0", { event: {}, env: {} })).toThrow(
      'calendar index down'
    )
  })

  it('HW-18 编译缓存不捕获实现：同一表达式先 0 后换成返回 2 的实现 → 结论跟着变', () => {
    const expression = "activeSessions('2026-10-24') > 1"
    setWhenHostFunctions({ activeSessions: () => 0 })
    expect(evaluateWhen(expression, { event: {}, env: {} })).toBe(false)
    setWhenHostFunctions({ activeSessions: () => 2 })
    expect(evaluateWhen(expression, { event: {}, env: {} })).toBe(true)
  })
})

/**
 * 每次求值换上的宿主函数（`evaluateWhen` 的第三个参数，排期预演用它假设「那天有会话」）：只给这一次求值，
 * 全局那份（真的触发源在用）原样留着 —— 求值抛错、桩抛错、结果不是布尔都一样换回去。
 */
describe('evaluateWhen 的 functions —— 只换这一次求值', () => {
  afterEach(() => {
    setWhenHostFunctions({})
  })

  const CALL = "activeSessions('2026-10-24') > 0"
  const ctx = { event: {}, env: {} }

  it('HW-19 传了桩 → 用桩（收到那个日期），全局的实现一次都不调', () => {
    const global = vi.fn((_date: string) => 0)
    const stub = vi.fn((_date: string) => 1)
    setWhenHostFunctions({ activeSessions: global })
    expect(evaluateWhen(CALL, ctx, { activeSessions: stub })).toBe(true)
    expect(stub).toHaveBeenCalledTimes(1)
    expect(stub).toHaveBeenCalledWith('2026-10-24')
    expect(global).not.toHaveBeenCalled()
  })

  it('HW-20 不漏到全局：带桩求值之后，不带桩的求值又回到全局实现（桩不再被调）', () => {
    const global = vi.fn((_date: string) => 0)
    const stub = vi.fn((_date: string) => 1)
    setWhenHostFunctions({ activeSessions: global })
    expect(evaluateWhen(CALL, ctx, { activeSessions: stub })).toBe(true)
    expect(evaluateWhen(CALL, ctx)).toBe(false)
    expect(global).toHaveBeenCalledTimes(1)
    expect(stub).toHaveBeenCalledTimes(1)
  })

  it.each<[string, string, () => number]>([
    ['表达式求值抛错（桩调过之后访问缺失属性）', `${CALL} && event.nope`, () => 1],
    [
      '桩自己抛错',
      CALL,
      () => {
        throw new Error('stub exploded')
      }
    ],
    ['结果不是布尔（int）', "activeSessions('2026-10-24')", () => 1]
  ])('HW-21 %s → evaluateWhen 抛，之后全局实现照旧在位', (_label, expression, impl) => {
    const global = vi.fn((_date: string) => 5)
    const stub = vi.fn(impl)
    setWhenHostFunctions({ activeSessions: global })
    expect(() => evaluateWhen(expression, ctx, { activeSessions: stub })).toThrow()
    expect(stub).toHaveBeenCalledTimes(1)
    expect(global).not.toHaveBeenCalled()
    expect(evaluateWhen("activeSessions('2026-10-24') == 5", ctx)).toBe(true)
    expect(global).toHaveBeenCalledTimes(1)
    expect(stub).toHaveBeenCalledTimes(1)
  })

  it('HW-22 全局没注入：带桩照样能求值；随后不带桩 → throw「not available on this host」', () => {
    setWhenHostFunctions({})
    expect(evaluateWhen(CALL, ctx, { activeSessions: () => 1 })).toBe(true)
    expect(() => evaluateWhen(CALL, ctx)).toThrow('not available on this host')
  })

  it('HW-23 functions = {} 不动全局：用的还是全局实现', () => {
    const global = vi.fn((_date: string) => 2)
    setWhenHostFunctions({ activeSessions: global })
    expect(evaluateWhen("activeSessions('2026-10-24') == 2", ctx, {})).toBe(true)
    expect(global).toHaveBeenCalledTimes(1)
  })

  it('HW-24 编译缓存不捕获实现：同一表达式 桩 / 全局 / 桩 交替，结论跟着变', () => {
    const expression = "activeSessions('2026-10-24') > 1"
    setWhenHostFunctions({ activeSessions: () => 0 })
    expect(evaluateWhen(expression, ctx, { activeSessions: () => 2 })).toBe(true)
    expect(evaluateWhen(expression, ctx)).toBe(false)
    expect(evaluateWhen(expression, ctx, { activeSessions: () => 3 })).toBe(true)
    expect(evaluateWhen(expression, ctx)).toBe(false)
  })

  it('HW-25 带桩时日期形状不对照样 throw「expects a local date like」，桩不被调用', () => {
    const stub = vi.fn((_date: string) => 1)
    expect(() =>
      evaluateWhen(
        'activeSessions(event.d) > 0',
        { event: { d: 'today' }, env: {} },
        {
          activeSessions: stub
        }
      )
    ).toThrow("expects a local date like '2026-10-24'")
    expect(stub).not.toHaveBeenCalled()
  })
})
