const autoTitle = (): NonNullable<ReturnType<typeof buildBuiltinWorkflow>> =>
  buildBuiltinWorkflow(AUTO_TITLE_WORKFLOW_SPEC, {})!

describe('auto-title — 结构钉板', () => {
  it('buildBuiltinWorkflows({}) 的内置清单是钉板：auto-title + bot-chat，都解析非 null', () => {
    // 保持 toEqual 的严格性 —— 内置清单多一条少一条都该在这里现形
    const all = buildBuiltinWorkflows({})
    expect(all.map((w) => w.name)).toEqual(['auto-title', 'bot-chat'])
    expect(autoTitle()).not.toBeNull()
  })

  it('绑定钉板：恰两条 —— quick（prompt-accepted + isDefaultTitle）与 refine（turn-completed + 三条件）', () => {
    const bindings = autoTitle().bindings
    expect(bindings).toHaveLength(2)
    expect(bindings[0].trigger).toBe('session.prompt-accepted')
    expect(bindings[0].when).toBe('event.isDefaultTitle')
    expect(bindings[1].trigger).toBe('session.turn-completed')
    expect(bindings[1].when).toContain('titleAutoGenerated')
    expect(bindings[1].when).toContain('turnCount == 2')
    expect(bindings[1].when).toContain('textMessageCount >= 3')
  })

  it('schemas.result：顶层 object 且 required=[title]', () => {
    const schema = autoTitle().schemas.result
    expect(schema.type).toBe('object')
    expect(schema.required).toEqual(['title'])
  })

  it('结构缺省钉板：concurrency skip、无 limits（模型跟随会话/被派发 agent 的声明）', () => {
    const wf = autoTitle()
    expect(wf.concurrency).toBe('skip')
    expect(wf.limits).toEqual({})
  })
})

// ── 真脚本端到端：AsyncFunction 引擎 + fake manager/档案 ──

const AsyncFunction = Object.getPrototypeOf(async () => {}).constructor as new (
  ...args: string[]
) => (...vals: unknown[]) => Promise<unknown>
const scriptEngine: WorkflowScriptEngine = {
  compile: () => ({ ok: true }),
  execute: async (source, api) =>
    new AsyncFunction(...Object.keys(api), source)(...Object.values(api))
}

const TITLER: InProcessAgentType = {
  name: 'titler',
  displayName: 'Titler',
  description: '',
  tools: ['session'],
  systemPrompt: 'You name chat sessions.'
}

function makeAutoTitleEngine(
  overrideRunTask?: (p: RunTaskParams) => Promise<{ result: string; structured?: unknown }>
): {
  engine: ReturnType<typeof createWorkflowEngine>
  runTask: ReturnType<typeof vi.fn>
  records: Array<Record<string, unknown>>
  metas: () => Array<Record<string, unknown>>
  waitEnd: (n?: number) => Promise<void>
} {
  const records: Array<Record<string, unknown>> = []
  const runTask = vi.fn(
    overrideRunTask ??
      (async () => ({
        result: JSON.stringify({ title: 'X' }),
        structured: { title: 'X' }
      }))
  )
  const entries: WorkflowRegistryEntry[] = [{ file: autoTitle(), source: 'builtin' }]
  const engine = createWorkflowEngine({
    manager: { runTask } as unknown as SubAgentManager,
    script: scriptEngine,
    listWorkflows: () => entries,
    resolveAgentProfile: (ref) => (ref === 'titler' ? TITLER : null),
    resolveRunModel: async () => ({ provider: 'p', model: 'm', capabilities: {} }),
    onRecord: (_name, _runId, rec) => records.push(rec),
    env: { host: 'desktop', platform: 'darwin' }
  })
  return {
    engine,
    runTask,
    records,
    metas: () => records.filter((r) => r.type === 'meta'),
    waitEnd: (n = 1) =>
      vi.waitFor(() => {
        expect(records.filter((r) => r.type === 'end').length).toBeGreaterThanOrEqual(n)
      })
  }
}

const promptPayload = (
  over: Partial<TriggerPayloadMap['session.prompt-accepted']> = {}
): TriggerPayloadMap['session.prompt-accepted'] => ({
  sessionId: 's1',
  profileName: 'default',
  title: 'New Chat',
  isDefaultTitle: true,
  promptText: 'hello',
  ...over
})

const turnPayload = (
  over: Partial<TriggerPayloadMap['session.turn-completed']> = {}
): TriggerPayloadMap['session.turn-completed'] => ({
  sessionId: 's1',
  profileName: 'default',
  title: 'Quick title',
  isDefaultTitle: false,
  titleAutoGenerated: true,
  turnCount: 2,
  textMessageCount: 3,
  recentText: 'User: a\nAssistant: b',
  ...over
})

describe('auto-title — quick 端到端（真脚本）', () => {
  it('prompt-accepted + isDefaultTitle → 派发 titler 恰一次，契约/描述/归属逐项落位，end ok:true', async () => {
    const { engine, runTask, records, waitEnd } = makeAutoTitleEngine()
    engine.fire('session.prompt-accepted', promptPayload())
    await waitEnd()

    expect(runTask).toHaveBeenCalledTimes(1)
    const params = runTask.mock.calls[0][0] as RunTaskParams
    expect(params.agentType.name).toBe('titler')
    expect(params.prompt).toContain('hello')
    expect(params.prompt).toContain('<conversation>')
    expect(params.description).toBe('session title')
    expect(params.resultContract?.schema).toEqual(autoTitle().schemas.result)
    expect(params.resultContract?.sourceLabel).toBe('auto-title')
    expect(params.parentSessionId).toBe('s1')

    const end = records.find((r) => r.type === 'end')!
    expect(end.ok).toBe(true)
    expect(end.output).toEqual({ title: 'X' })
    expect(records.some((r) => r.type === 'log' && r.message === 'title applied: X')).toBe(true)
  })

  it('quick 反例：isDefaultTitle:false → 零派发', async () => {
    const { engine, runTask, records } = makeAutoTitleEngine()
    engine.fire('session.prompt-accepted', promptPayload({ isDefaultTitle: false }))
    expect(records).toEqual([])
    expect(runTask).not.toHaveBeenCalled()
  })
})

describe('auto-title — refine 端到端（真脚本）', () => {
  it('turn-completed 三条件齐 → 派发且 prompt 含 recentText', async () => {
    const { engine, runTask, waitEnd } = makeAutoTitleEngine()
    engine.fire('session.turn-completed', turnPayload())
    await waitEnd()
    expect(runTask).toHaveBeenCalledTimes(1)
    expect((runTask.mock.calls[0][0] as RunTaskParams).prompt).toContain('User: a\nAssistant: b')
  })

  it.each([
    ['titleAutoGenerated:false', { titleAutoGenerated: false }],
    ['turnCount 1', { turnCount: 1 }],
    ['turnCount 3', { turnCount: 3 }],
    ['textMessageCount 2', { textMessageCount: 2 }]
  ])('refine 反例 %s → 零派发', (_label, over) => {
    const { engine, runTask, records } = makeAutoTitleEngine()
    engine.fire('session.turn-completed', turnPayload(over))
    expect(records).toEqual([])
    expect(runTask).not.toHaveBeenCalled()
  })
})

describe('auto-title — 摘录裁尾', () => {
  it('promptText 2000 字 → 发出的 prompt 里 <conversation> 摘录 ≤1000 字', async () => {
    const { engine, runTask, waitEnd } = makeAutoTitleEngine()
    engine.fire('session.prompt-accepted', promptPayload({ promptText: 'x'.repeat(2000) }))
    await waitEnd()
    const prompt = (runTask.mock.calls[0][0] as RunTaskParams).prompt
    const excerpt = /<conversation>\n([\s\S]*?)\n<\/conversation>/.exec(prompt)?.[1]
    expect(excerpt).toBeDefined()
    expect(excerpt!.length).toBeLessThanOrEqual(1000)
  })
})

describe('auto-title — 分道（M2′ 顺带修掉的既有缺陷）', () => {
  /** 挂起的 titler 派发：测试端显式放行 */
  const gatedTitler = (
    gates: Array<() => void>
  ): (() => Promise<{ result: string; structured?: unknown }>) => {
    return () =>
      new Promise((resolve) =>
        gates.push(() =>
          resolve({ result: JSON.stringify({ title: 'X' }), structured: { title: 'X' } })
        )
      )
  }

  it('迁移承诺：md 一字未改 —— 两条绑定都没有 key，缺省键由埋点 scope 推导', () => {
    expect(autoTitle().bindings.every((b) => b.key === undefined)).toBe(true)
  })

  it('两个会话同时 turn-completed → 各起一个 run（refine 是一次性窗口，被 skip 即永久丢标题）', async () => {
    const gates: Array<() => void> = []
    const { engine, runTask, metas, waitEnd } = makeAutoTitleEngine(gatedTitler(gates))

    engine.fire('session.turn-completed', turnPayload({ sessionId: 's1' }))
    engine.fire('session.turn-completed', turnPayload({ sessionId: 's2' }))
    await vi.waitFor(() => expect(gates).toHaveLength(2))

    expect(metas().map((m) => m.lane)).toEqual(['auto-title\u0000s1', 'auto-title\u0000s2'])
    expect(runTask).toHaveBeenCalledTimes(2)

    gates.forEach((release) => release())
    await waitEnd(2)
  })

  it('同一会话内 quick 与 refine 仍互斥（同道按文件策略 skip）', async () => {
    const gates: Array<() => void> = []
    const { engine, metas, waitEnd } = makeAutoTitleEngine(gatedTitler(gates))

    engine.fire('session.prompt-accepted', promptPayload({ sessionId: 's1' }))
    await vi.waitFor(() => expect(gates).toHaveLength(1))
    engine.fire('session.turn-completed', turnPayload({ sessionId: 's1' }))

    expect(metas()).toHaveLength(1)
    gates[0]()
    await waitEnd()
  })
})

describe('bot-chat — 骨架管线的结构钉板', () => {
  const botChat = (): ParsedWorkflowFile =>
    buildBuiltinWorkflows({}).find((w) => w.name === 'bot-chat')!

  it('没有任何埋点绑定 —— 它只由会话按名 invoke', () => {
    expect(botChat().bindings).toEqual([])
  })

  it('concurrency 为 parallel：引擎重入彻底让位，独占由宿主的 turn() 提供', () => {
    // 这两件事是**两个粒度**：引擎重入管「要不要起 run」，mailbox 管「已在跑的 run
    // 何时进独占段」。声明 parallel 才不会让两者打架
    expect(botChat().concurrency).toBe('parallel')
  })

  it('四个契约块齐全且都是 type:object（M5′/M8′ 直接消费，此刻已是最终形态）', () => {
    const schemas = botChat().schemas
    expect(Object.keys(schemas).sort()).toEqual(['intent', 'intentSolo', 'recheck', 'reply'])
    for (const [name, schema] of Object.entries(schemas)) {
      expect((schema as { type?: string }).type, name).toBe('object')
    }
  })

  it('intent 有 ignore、intentSolo 没有 —— 1:1 会话里沉默与坏掉分不开', () => {
    const enumOf = (n: string): string[] =>
      (botChat().schemas[n] as Record<string, Record<string, Record<string, string[]>>>).properties
        .decision.enum ?? []
    expect(enumOf('intent')).toContain('ignore')
    expect(enumOf('intentSolo')).not.toContain('ignore')
  })

  it('脚本一律读 input.* —— 脚本作用域不平铺 input（裸名是 ReferenceError）', () => {
    const script = botChat().script
    // 平铺只发生在提示词块的渲染作用域；脚本 global 只有基础 API + 调用方装配的那几个
    for (const field of [
      'occasion',
      'window',
      'notes',
      'agents.intent',
      'session.directed',
      'session.others'
    ]) {
      expect(script, field).toContain(`input.${field}`)
    }
    // 反过来：新消息的正文脚本一次都不碰 —— 它经模板的 {{message.text}} 进提示词，
    // 那里的作用域才是平铺的。脚本只挑材料，不拼文案
    expect(script).not.toContain('input.message.text')
    expect(botChat().prompts.gate).toContain('{{message.text}}')
    // 两个装配进来的函数都用上了 —— 它们正是「这份 md 是 bot 管线」的全部含义。
    // v2 取消仲裁后 claim 一并消失：没有竞争就没有「这条归谁」要裁
    for (const api of ['turn(', 'say(']) expect(script).toContain(api)
    expect(script).not.toContain('claim(')
  })

  it('故障与被中止分开：step_aborted 安静退出，另两种才算门控故障', () => {
    // 「有人赢了 / 会话停了」不是「门控坏了」—— 把它算进破损计数会让正常的多 bot 让位
    // 两次之后把 bot 打成回落态
    const script = botChat().script
    expect(script).toContain('step_aborted')
    expect(script).toContain('next_not_called')
    expect(script).toContain('step_timeout')
  })

  it("脚本里每个 prompt('x') 的 x 都真有对应的块（改名漏一处 = 运行时抛）", () => {
    const wf = botChat()
    const used = [...wf.script.matchAll(/prompt\('([A-Za-z][\w-]*)'/g)].map((m) => m[1])
    expect(used.length).toBeGreaterThan(0)
    for (const name of new Set(used)) {
      expect(Object.keys(wf.prompts), name).toContain(name)
    }
  })

  it('可选上下文是嵌套 prompt 块，不是裸占位符', () => {
    // 模板语法只有 {{path}}（无条件无循环），而「整行消失」只在该行除占位符外全是空白时
    // 成立 —— 所以「有内容才出现的一整段」必须整体是一个值，标题得住在值**里面**
    const wf = botChat()
    for (const optional of ['notes', 'others', 'addressed', 'window', 'since']) {
      expect(Object.keys(wf.prompts), optional).toContain(optional)
    }
    expect(wf.prompts.notes).toContain('##')
    expect(wf.script).toContain("prompt('notes'")
  })
})

/**
 * 任务段（M8′）落地之后 bot-chat 的结构面。行为面在 botChatTask.test.ts 真跑，这里只钉
 * **md 上肉眼可查、改了就该有人知道**的那几处：默认值、契约形状、以及两条刻意的「不写」
 * （任务段不给 tools、提示词不宣告附件）——「刻意不写」是最容易在下一次编辑里被好心补上的。
 */
describe('bot-chat —— 任务段与 BotReply 的结构钉板', () => {
  const botChat = (): ParsedWorkflowFile =>
    buildBuiltinWorkflows({}).find((w) => w.name === 'bot-chat')!

  it('BC-1 vars 数值钉板：两个窗口、三个墙钟、笔记预算与出队复核开关', () => {
    // 数值本身没有神圣性，但它们是 e2e 与单测里一堆断言的依据（切片条数、超时秒数），
    // 改一个就该在这里显形一次
    expect(botChat().vars).toEqual({
      gateWindow: 8,
      taskWindow: 20,
      gateTimeoutSec: 60,
      taskTimeoutSec: 1800,
      notesTimeoutSec: 300,
      notesWindow: 60,
      notesBudget: 2000,
      recheckStale: true
    })
  })

  it('BC-2 limits：agent 上限 4、墙钟 2400s —— 必须宽于最长的单步（taskTimeoutSec）', () => {
    const wf = botChat()
    expect(wf.limits).toEqual({ maxAgents: 4, maxDurationSec: 2400 })
    // run 级墙钟若短于单步墙钟，任务段永远等不到自己的超时，出声的就成了笼统的 run 失败
    expect(wf.limits.maxDurationSec!).toBeGreaterThan(wf.vars.taskTimeoutSec as number)
  })

  it('BC-3 reply 契约恰六键，required 只有 headline（结论先行是唯一的硬要求）', () => {
    const reply = botChat().schemas.reply as {
      required?: string[]
      properties?: Record<string, unknown>
    }
    expect(reply.required).toEqual(['headline'])
    expect(Object.keys(reply.properties!).sort()).toEqual([
      'body',
      'followups',
      'headline',
      'points',
      'status',
      'table'
    ])
  })

  it('BC-4 【契约↔投影闭环】reply 契约里的每个键都能在 markdown 投影里留下痕迹', () => {
    // 契约多出一个投影不认识的键，模型就会去填一个既不进 content 也不上屏的字段 ——
    // 让它填等于骗它。这条把 md 那份 JSON Schema 与 chat-protocol 的投影拴在一起，
    // 两边任何一侧单方面加键都在这里现形
    const sample: Record<string, unknown> = {
      headline: '结论一句',
      body: '一段解释',
      points: ['要点甲'],
      table: { columns: ['列甲'], rows: [['格甲']] },
      status: 'warn',
      followups: ['接着问什么']
    }
    const traces: Record<string, string> = {
      headline: '结论一句',
      body: '一段解释',
      points: '要点甲',
      table: '列甲',
      status: 'Status: warn',
      followups: '接着问什么'
    }
    const reply = botChat().schemas.reply as { properties: Record<string, unknown> }
    for (const key of Object.keys(reply.properties)) {
      expect(Object.keys(sample), key).toContain(key)
      const single = { headline: '结论一句', [key]: sample[key] } as BotReply
      expect(botReplyToMarkdown(single), key).toContain(traces[key])
    }
    // table 的行列都得声明出来，否则模型会交回半张表而投影只能整段丢掉它
    const table = reply.properties.table as { required?: string[] }
    expect(table.required).toEqual(['columns', 'rows'])
  })

  it('BC-5 【刻意不写】任务段的 run 没有 tools 选项 —— 门控与复核才有', () => {
    // 收窄任务段的工具等于推翻 bot md 关于它自己的说法（它的正文就是按那份清单写的）；
    // 门控是共享内置件，锁成零工具才防得住用户覆盖它之后长出工具
    const script = botChat().script
    const gateCall = script.slice(script.indexOf('1 ── The gate'), script.indexOf('2 ── A broken'))
    const taskCall = script.slice(
      script.indexOf('6 ── The work itself'),
      script.indexOf('} catch (e) {\n    const code = e && e.code\n    // Someone stopped')
    )
    expect(gateCall).toContain('tools: []')
    expect(taskCall).not.toContain('tools:')
    expect(taskCall).toContain('schema: schemas.reply')
  })

  it('BC-6 【刻意不写】没有 attached 提示词块，也没有任何一句宣告附件张数', () => {
    // 取不到附件时那句话就是在诱导幻觉，而图片本来就以 user 消息的形式在上下文里
    const wf = botChat()
    expect(Object.keys(wf.prompts)).not.toContain('attached')
    for (const [name, body] of Object.entries(wf.prompts)) {
      expect(body, name).not.toMatch(/attach|image/i)
    }
    // 转交本身仍在：句柄经 run 的 attach 选项走，不经提示词
    expect(wf.script).toContain('attach: attached')
    expect(wf.script).toContain('input.message && input.message.attachments')
  })

  it('BC-7 【刻意不写】任务段提示词不带 notesBlock —— 任务段 agent 就是 bot 自己', () => {
    const script = botChat().script
    const taskPrompt = script.slice(script.indexOf("prompt('task'"), script.indexOf('sinceBlock:'))
    expect(taskPrompt).not.toContain('notesBlock')
    // 对照：门控段是共享内置件，它必须被告知这个 bot 学过什么
    expect(script).toContain('notesBlock: notesBlock')
    expect(botChat().prompts.task).not.toContain('{{notesBlock}}')
    expect(botChat().prompts.gate).toContain('{{notesBlock}}')
  })

  it('BC-8 失败文案齐备：四种任务段结局各有自己的一句话', () => {
    // 「配置错」「超时」「跑挂了」「没形状」对用户的意味完全不同，共用一句就等于让人
    // 去猜下一步该做什么
    for (const name of ['taskNoAgent', 'taskTimeout', 'taskFailed', 'gateBroken', 'gateTimeout']) {
      expect(Object.keys(botChat().prompts), name).toContain(name)
      expect(botChat().prompts[name].trim(), name).not.toBe('')
    }
    expect(botChat().prompts.taskNoAgent).toContain('{{agent}}')
  })
})
