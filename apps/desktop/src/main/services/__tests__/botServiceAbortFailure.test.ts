// ────────────────────────── AB：per-bot 停止 ──────────────────────────

describe('AB —— abortBot（粒度到 (bot, 消息)）', () => {
  it('A2-B7 命中在飞票 → true，且门控住的 invoke 的 req.signal 落下', async () => {
    const g = gateCalls()
    const msg = prompt('停我这条')
    await g.wait(1)
    const messageId = g.calls[0].input.message.id
    expect(g.calls[0].signal.aborted).toBe(false)

    expect(botService.abortBot(SID, 'scout', messageId)).toBe(true)
    expect(g.calls[0].signal.aborted).toBe(true)

    g.calls[0].finish()
    await msg
  })

  it('A2-B8 messageId / botName / sessionId 任一不匹配 → false，signal 不动', async () => {
    const g = gateCalls()
    const msg = prompt('别人停不了我')
    await g.wait(1)
    const messageId = g.calls[0].input.message.id

    expect(botService.abortBot(SID, 'scout', 'not-this-message')).toBe(false)
    expect(botService.abortBot(SID, 'ranger', messageId)).toBe(false)
    expect(botService.abortBot('another-session', 'scout', messageId)).toBe(false)
    expect(g.calls[0].signal.aborted).toBe(false)

    g.calls[0].finish()
    await msg
  })

  it('A2-B9 中止后 {started:true, ok:false} 收尾 → 无 runFailed 气泡；run_end 照记、turn-completed 照 fire', async () => {
    // §9.1：用户按的停止不是「无从解释的沉默」—— 兜底气泡被 !signal.aborted 守卫压掉，
    // 但这一轮的账（run_end 决策、轮结束埋点）一分不少
    const g = gateCalls()
    const msg = prompt('停了别再道歉')
    await g.wait(1)
    botService.abortBot(SID, 'scout', g.calls[0].input.message.id)

    g.calls[0].finish({ started: true, ok: false, error: 'aborted by user' })
    await msg

    const msgs = await messageService.listBySession(SID)
    expect(msgs.filter((m) => m.role === 'assistant')).toHaveLength(0)
    expect(msgs.some((m) => m.content === 'bot.runFailed')).toBe(false)
    expect(kindsOf('scout')).toContain('run_end')
    expect(fired('session.turn-completed')).toHaveLength(1)
  })

  it('A2-B10 同 bot 两条消息在飞：abortBot(msg1) 只落 msg1 的 signal，msg2 照常 say 落树', async () => {
    const g = gateCalls()
    const m1 = prompt('第一条')
    await g.wait(1)
    const m2 = prompt('第二条')
    await g.wait(2)

    botService.abortBot(SID, 'scout', g.calls[0].input.message.id)
    expect(g.calls[0].signal.aborted).toBe(true)
    expect(g.calls[1].signal.aborted).toBe(false)

    // 被停的那条不说话收尾；另一条照常 say —— 粒度是 (bot, 消息)，不是整个 bot
    g.calls[0].finish({ started: true, ok: false })
    await expect(g.calls[1].api.say('第二条照常回答')).resolves.toMatchObject({
      messageId: expect.any(String)
    })
    g.calls[1].finish()
    await Promise.all([m1, m2])

    const replies = (await messageService.listBySession(SID)).filter((m) => m.role === 'assistant')
    expect(replies.map((m) => m.content)).toEqual(['第二条照常回答'])
  })
})

// ────────────────────────── SE：say 的 error 选项 ──────────────────────────

describe('SE —— say(…, { error }) 写进署名侧车', () => {
  /** 单 bot 会话跑一轮，让脚本侧调一次 say 后正常收尾 */
  async function sayOnce(raw: unknown, opts?: unknown): Promise<void> {
    const g = gateCalls()
    const msg = prompt('说一句')
    await g.wait(1)
    await g.calls[0].api.say(raw, opts)
    g.calls[0].finish()
    await msg
  }

  it('A2-B11 say("x", {error:true, decision:"clarify"})：侧车有 error:true、**无** decision 键', async () => {
    // 降级出声绝不带 decision —— 否则一条 clarify 会把用户的下一条无关消息
    // 硬路由回这个刚出过故障的 bot
    await sayOnce('x', { error: true, decision: 'clarify' })

    const data = await lastSidecarData()
    expect(data.error).toBe(true)
    expect(data).not.toHaveProperty('decision')
    expect(data).toMatchObject({ botName: 'scout', displayName: 'Scout' })
  })

  it('A2-B12 say("x", {error:"true"})：赃值不上车 —— 侧车无 error 键；decision 照常写入', async () => {
    // error 的收窄口径是 === true：字符串 "true" 不算降级出声，
    // 于是「不带 decision」那条纪律也不触发
    await sayOnce('x', { error: 'true', decision: 'clarify' })

    const data = await lastSidecarData()
    expect(data).not.toHaveProperty('error')
    expect(data.decision).toBe('clarify')
  })

  it('A2-B13 say(结构化, {error:true})：reply 与 error 共存 —— 降级通告也可以带结构', async () => {
    await sayOnce({ headline: '出错但有结构', body: '带着结构的降级通告。' }, { error: true })

    const data = await lastSidecarData()
    expect(data.error).toBe(true)
    expect(data.reply).toMatchObject({ headline: '出错但有结构', body: '带着结构的降级通告。' })
  })
})

// ────────────────────────── HF：三处宿主失败落点 ──────────────────────────

/**
 * 三处宿主失败都要把 error 写进侧车、投影成 `metadata.botFailure === true` ——
 * 每条换新 bot 名（gateHealth 是进程级 sticky 的，且不该为测试开复位后门）。
 */
describe('HF —— 宿主失败落树带 error', () => {
  it('A2-B14a 管线缺失的可见失败 → metadata.botFailure === true', async () => {
    mocks.hasWorkflow.mockImplementation((name: string) => name !== 'nope-flow')
    writeBot('hf-miss', { displayName: 'Miss', pipeline: 'nope-flow' })
    seedSession(['hf-miss'])
    await prompt('这条没人接得住')

    await vi.waitFor(async () => {
      const msgs = await messageService.listBySession(SID)
      const bubble = msgs.find((m) => m.content === 'bot.pipelineMissing')
      expect(bubble).toBeDefined()
      expect((bubble!.metadata as { botFailure?: unknown }).botFailure).toBe(true)
    })
  })

  it('A2-B14b runFailed 兜底气泡 → metadata.botFailure === true', async () => {
    writeBot('hf-fail', { displayName: 'Fail' })
    seedSession(['hf-fail'])
    mocks.invoke.mockResolvedValue({ started: true, ok: false, error: 'boom' })
    await prompt('这条会失败')

    await vi.waitFor(async () => {
      const msgs = await messageService.listBySession(SID)
      const bubble = msgs.find((m) => m.content === 'bot.runFailed')
      expect(bubble).toBeDefined()
      expect((bubble!.metadata as { botFailure?: unknown }).botFailure).toBe(true)
    })
  })

  it('A2-B14c 门控回落提示 → metadata.botFailure === true（脱手 .catch 落树，须 waitFor）', async () => {
    writeBot('hf-gate', { displayName: 'Gate' })
    seedSession(['hf-gate'])
    mocks.invoke.mockResolvedValue(ran({ gate: 'broken', outcome: 'gate-broken' }))
    await prompt('一')
    await prompt('二')

    // 回落提示刻意不在这一轮的关键路径上（.catch 而非 await）—— 等它落定
    await vi.waitFor(async () => {
      const msgs = await messageService.listBySession(SID)
      const bubble = msgs.find((m) => m.content === 'bot.gateFallback')
      expect(bubble).toBeDefined()
      expect((bubble!.metadata as { botFailure?: unknown }).botFailure).toBe(true)
    })
  })
})

// ────────────────────────── BR：广播与重开同源 ──────────────────────────

describe('BR —— error 消息的广播与 message.list 同源', () => {
  it('A2-B15 appendBotMessage(error:true) 的 assistant_message 与 message.list 同 id 逐字段全等，botFailure === true', async () => {
    const id = await botService.appendBotMessage(
      SID,
      { botName: 'scout', displayName: 'Scout', error: true },
      { content: '⚠️ 这条没办成' }
    )
    expect(id).toBeTruthy()

    const evt = broadcasts('assistant_message').find((e) => e.messageId === id)!
    expect(evt).toBeDefined()
    const streamed = JSON.parse(evt.message as string) as ChatMessage
    const reopened = (await messageService.listBySession(SID)).find((m) => m.id === id)

    // 流式所见即重开所见 —— botFailure 若只在其中一条路径上成型，刷新一下失败卡就没了
    expect(reopened).toEqual(streamed)
    expect((streamed.metadata as { botFailure?: unknown }).botFailure).toBe(true)
  })
})
