/** 某个埋点 id 的全部 payload */
const fired = (id: string): Array<Record<string, unknown>> =>
  mocks.fire.mock.calls.filter((c) => c[0] === id).map((c) => c[1] as Record<string, unknown>)

/** 某个 bot 的决策记录 kind 序列 */
function kindsOf(botName: string): string[] {
  const file = join(dirs.bots, '.runs', botName, 'decisions.jsonl')
  if (!existsSync(file)) return []
  return readFileSync(file, 'utf-8')
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((l) => String((JSON.parse(l) as Record<string, unknown>).kind))
}

/** 广播出去的 ChatEvent（按 type 过滤） */
const broadcasts = (type: string): Array<Record<string, unknown>> =>
  mocks.broadcast.mock.calls
    .map((c) => c[0] as Record<string, unknown>)
    .filter((e) => e.type === type)

const ran = (
  output: Record<string, unknown> = { gate: 'ok', outcome: 'reply' }
): Record<string, unknown> => ({ started: true, ok: true, output })

/** 一次被门控住的 invoke 调用 —— 记下票面（input / signal / extraApi），由测试放行 */
interface GatedCall {
  input: { message: { id: string } }
  signal: AbortSignal
  api: {
    say: (raw: unknown, opts?: unknown) => Promise<{ messageId: string | null }>
  }
  finish: (result?: Record<string, unknown>) => void
}

/**
 * 逐调用门控：每次 invoke 挂起并记录，由测试逐个放行。
 * **每个拿到的 call 都必须 finish** —— 否则这条会话永远在飞（收尾纪律）。
 */
function gateCalls(): { calls: GatedCall[]; wait: (n: number) => Promise<void> } {
  const calls: GatedCall[] = []
  mocks.invoke.mockImplementation(
    (req: {
      input: { message: { id: string } }
      signal: AbortSignal
      extraApi: GatedCall['api']
    }) =>
      new Promise((resolve) => {
        calls.push({
          input: req.input,
          signal: req.signal,
          api: req.extraApi,
          finish: (result = ran()) => resolve(result)
        })
      })
  )
  return {
    calls,
    wait: (n) => vi.waitFor(() => expect(calls.length).toBeGreaterThanOrEqual(n))
  }
}

const prompt = (text = 'hello'): Promise<void> =>
  botService.handleUserMessage({ sessionId: SID, text } as never)

/** 表里最后一条 bot 行 —— v2 的「原始存储」就是这一行（decision / error 都是列） */
async function lastSidecarData(): Promise<Record<string, unknown>> {
  const { chatMessageDao } = await import('./fakeChatMessageDao')
  const row = chatMessageDao.findLastBot(SID)
  if (!row) throw new Error('no bot message')
  return {
    botName: row.botName,
    displayName: row.displayName,
    ...(row.decision ? { decision: row.decision } : {}),
    ...(row.reply ? { reply: JSON.parse(row.reply) } : {}),
    ...(row.isError ? { error: true } : {})
  } as Record<string, unknown>
}

