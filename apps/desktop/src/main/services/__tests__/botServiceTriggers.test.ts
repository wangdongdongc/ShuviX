/** 某个埋点 id 的全部 payload */
const fired = (id: string): Array<Record<string, unknown>> =>
  mocks.fire.mock.calls.filter((c) => c[0] === id).map((c) => c[1] as Record<string, unknown>)

/** 某个 bot 的决策记录（一行一条 JSON） */
function decisions(botName: string): Array<Record<string, unknown>> {
  const file = join(dirs.bots, '.runs', botName, 'decisions.jsonl')
  if (!existsSync(file)) return []
  return readFileSync(file, 'utf-8')
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l) as Record<string, unknown>)
}

const kindsOf = (botName: string): string[] => decisions(botName).map((d) => String(d.kind))

/** 一次管线 invoke 的结果 —— 缺省「跑完了，门控正常」 */
const ran = (
  output: Record<string, unknown> = { gate: 'ok', outcome: 'reply' }
): { started: boolean; ok: boolean; output: Record<string, unknown> } => ({
  started: true,
  ok: true,
  output
})

/** 拿住写锁并卡住，返回释放函数 —— 用来造「在飞」的确定性窗口 */
function holdLock(sid?: string): { release: () => void; done: Promise<void> } {
  const target = sid ?? SID
  let release: () => void = () => {}
  const gate = new Promise<void>((r) => {
    release = r
  })
  return { release, done: withSessionTreeLock(target, () => gate, dirs.sessions) }
}

/**
 * 让 invoke 挂起，返回放行函数。
 *
 * 放行是**一次性开闸**而不是「把此刻排队的放掉」：管线起跑要经过落树 + 投影 + 窗口构建
 * 好几个 await，测试端很难精确等到那一刻，而漏掉一次尚未到达的 invoke 就会让这条会话
 * 永远停在在飞状态 —— 表现为一条与被测行为毫无关系的超时。
 */
function gateInvoke(output: Record<string, unknown> = { gate: 'ok', outcome: 'reply' }): {
  release: () => void
} {
  const waiters: Array<() => void> = []
  let open = false
  mocks.invoke.mockImplementation(() =>
    open
      ? Promise.resolve(ran(output))
      : new Promise((resolve) => waiters.push(() => resolve(ran(output))))
  )
  return {
    release: () => {
      open = true
      for (const w of waiters.splice(0)) w()
    }
  }
}

