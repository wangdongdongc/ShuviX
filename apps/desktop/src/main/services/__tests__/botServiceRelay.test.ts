/**
 * bot→bot 接力的**宿主侧**接线（v2 的第二根轴 `shuvix-bot-respond-to` 落到运行时）。
 *
 * L0 门自己怎么判「谁参与」有它的纯函数单测（`bot/__tests__/botGate.test.ts`）；这一层
 * 问的是另外三件事，每一件失手都不会报错，只会在真实会话里表现成一句难查的抱怨：
 *
 *  - **短路**：没有任何别的成员声明 `all` 时，一条 bot 消息必须一步都不往下走 ——
 *    否则每条回复都白跑一遍全员 L0 + 目录全扫，症状只是「变慢了」；
 *  - **脱手**：接力由某个 bot 的 `say` 触发，`await` 它等于把接力做成同步递归 ——
 *    症状是最先说话的那个 bot 一直「在输入中」，直到整条链路跑完；
 *  - **两个计数的传递**：`rootId` 认的是「同一棵传播树」，`hop` 认的是深度。root 被换掉，
 *    每跳都重新起算 8 条，maxFanout 形同虚设；hop 传错，链路要么早断要么不收敛。
 *
 * mock 面照抄 botServiceTriggers：workflowService / sessionService / paths / logger /
 * i18n / 广播出口是假的，**消息表与决策日志是真的**（内存版 DAO + 临时目录里的 jsonl）——
 * 这一组的断言几乎全在「到底落了什么行、记了什么决策」上。
 *
 * 额外多一层假：`bot/botGate` 被包了一层**透传**的探针（真件照跑，只是把入参录下来），
 * 因为 `author` / `hop` / `fanout` 这三个接力事实除此之外没有观测口 —— 它们既不进消息行
 * 也不进 invoke 的 input。
 */
