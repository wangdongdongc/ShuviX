function writeBot(
  name: string,
  opts: { displayName?: string; respond?: string; respondTo?: string } = {}
): void {
  mkdirSync(dirs.bots, { recursive: true })
  const lines = ['---', 'shuvix: bot v1', `name: ${name}`, `description: relay bot ${name}`]
  if (opts.displayName) lines.push(`shuvix-displayName: ${opts.displayName}`)
  if (opts.respond) lines.push(`shuvix-bot-respond: ${opts.respond}`)
  if (opts.respondTo) lines.push(`shuvix-bot-respond-to: ${opts.respondTo}`)
  lines.push('---', '', 'BOT BODY.')
  writeFileSync(join(dirs.bots, `${name}.md`), lines.join('\n'))
}

